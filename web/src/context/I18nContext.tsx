export type Language = keyof typeof messages
const catalogs = messages as Record<Language, Record<string, string>>
const availableLanguages = Object.keys(messages) as Language[]

interface I18nContextValue {
    language: Language;
    availableLanguages: Language[];
    setLanguage: (language: Language) => void;
    t: Translator
}

const I18nContext = createContext<I18nContextValue | null>(null)
const LANGUAGE_KEY = 'family-manager.language'

function initialLanguage(): Language {
    const storedLanguage = localStorage.getItem(LANGUAGE_KEY)
    return availableLanguages.find((language) => language === storedLanguage) ?? availableLanguages[0]
}

export function I18nProvider({children}: { children: ReactNode }) {
    const [language, setLanguage] = useState<Language>(initialLanguage)
    useEffect(() => {
        document.documentElement.lang = language
        localStorage.setItem(LANGUAGE_KEY, language)
    }, [language])

    const t = useMemo<Translator>(() => (key, values) => {
        const template = catalogs[language][key] ?? catalogs[availableLanguages[0]][key] ?? key
        return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(values?.[name] ?? ''))
    }, [language])

    const value = useMemo(() => ({language, availableLanguages, setLanguage, t}), [language, t])
    return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
    const context = useContext(I18nContext)
    if (!context) throw new Error('useI18n deve essere utilizzato all’interno di I18nProvider')
    return context
}
